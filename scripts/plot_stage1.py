#!/usr/bin/env python3
"""Plot the actual stage-1 FITS products; run full-table reads on compute nodes.

Usage: python scripts/plot_stage1.py --run-dir data/stage1_v1 --output-dir figures/stage1
No model predictions or artificial scientific data are generated by this script.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import fitsio
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm
import numpy as np


BLUE = "#26649B"
ORANGE = "#C36C2D"
GOLD = "#A58525"
PURPLE = "#80629B"
GRAY = "#73777B"
SPLITS = [(0, "Train", BLUE), (1, "Validation", GOLD),
          (2, "Spatial test", PURPLE), (3, "External reserved", ORANGE)]
MAX_SCATTER = 200_000


def read_table(run_dir: Path, name: str, columns: list[str]) -> np.ndarray:
    path = run_dir / "tables" / f"{name}.fits"
    if not path.is_file():
        raise FileNotFoundError(f"Missing actual stage-1 table: {path}")
    with fitsio.FITS(str(path)) as hdus:
        names = {x.lower(): x for x in hdus[1].get_colnames()}
        missing = [x for x in columns if x.lower() not in names]
        if missing:
            raise ValueError(f"{path.name} lacks required plot columns: {missing}")
        data = hdus[1].read(columns=[names[x.lower()] for x in columns])
    data.dtype.names = tuple(x.lower() for x in data.dtype.names)
    return data


def sample_indices(data: np.ndarray, limit: int = MAX_SCATTER) -> np.ndarray:
    """Deterministic splitmix64 sampling; never cast 64-bit IDs through float."""
    if len(data) <= limit:
        return np.arange(len(data))
    ids = np.asarray(data["ls_id"], dtype=np.uint64).copy()
    missing = ids == 0
    ids[missing] = np.asarray(data["source_id"][missing], dtype=np.uint64)
    missing = ids == 0
    ids[missing] = np.flatnonzero(missing).astype(np.uint64)
    with np.errstate(over="ignore"):
        h = ids + np.uint64(0x9E3779B97F4A7C15)
        h = (h ^ (h >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        h = (h ^ (h >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        h ^= h >> np.uint64(31)
    chosen = np.argpartition(h, limit - 1)[:limit]
    return chosen[np.argsort(h[chosen], kind="stable")]


def save_figure(fig: plt.Figure, output_dir: Path, filename: str,
                caption: str, *, bottom: float = 0.12) -> str:
    fig.text(0.045, 0.025, caption, fontsize=9, ha="left", va="bottom", linespacing=1.4)
    fig.tight_layout(rect=(0.025, bottom, 0.985, 0.95), h_pad=2, w_pad=2.4)
    path = output_dir / filename
    fig.savefig(path, dpi=170, facecolor="white")
    plt.close(fig)
    return str(path)


def empty_axis(ax: plt.Axes, message: str = "No finite eligible measurements") -> None:
    ax.text(0.5, 0.5, message, ha="center", va="center", transform=ax.transAxes,
            color=GRAY, fontsize=11)


def plot_counts(summary: dict, output_dir: Path) -> tuple[str, dict]:
    counts = summary.get("counts")
    if not isinstance(counts, dict):
        raise ValueError("summary.json must contain a counts dictionary")
    groups = [
        [("raw_rows_inspected", "All inspected sweep rows"),
         ("domain_psf", "PSF sources in selected domain"),
         ("grz_base", "Usable grz photometry"),
         ("gaia_matched", "Matched Gaia sources")],
        [("anchor", "High-quality Gaia anchors"),
         ("extended", "Extended Gaia sample"),
         ("spectroscopy", "Spectroscopic auxiliary sample"),
         ("external_reserved", "External reserved sample"),
         ("negative_parallax", "Negative parallaxes")],
    ]
    fig, axes = plt.subplots(1, 2, figsize=(13.2, 5.4))
    fig.suptitle("Stage 1 — full catalog counts", fontsize=16)
    plotted = {}
    for ax, group, title in zip(axes, groups, ["Input selection", "Sample layers (may overlap)"]):
        entries = [(key, label, int(counts[key])) for key, label in group if key in counts]
        if not entries:
            raise ValueError(f"No supported summary count keys for {title}")
        if any(value < 0 for _, _, value in entries):
            raise ValueError("Negative row count in summary.json")
        values = np.array([x[2] for x in entries])
        positive = values > 0
        y = np.arange(len(entries))
        ax.scatter(np.maximum(values, 1), y, s=65, color=BLUE, zorder=3)
        ax.set_xscale("log")
        lower = max(0.5, values[positive].min() / 2) if positive.any() else 0.5
        upper = max(10, values.max() * 15)
        if (~positive).any():
            lower = 0.5
        ax.set_xlim(lower, upper)
        for row, (key, _, value) in enumerate(entries):
            ax.annotate(f"{value:,}", (max(value, 1), row), xytext=(8, 0),
                        textcoords="offset points", va="center", fontsize=10)
            plotted[key] = value
        ax.set_yticks(y, [x[1] for x in entries])
        ax.invert_yaxis()
        ax.set_ylim(len(entries) - 0.5, -0.5)
        ax.grid(axis="x", alpha=0.18)
        ax.set_xlabel("Rows / sources, as recorded in summary.json (log scale)")
        ax.set_title(title, fontsize=12)
    caption = ("Exact counts from the complete processing audit; no figure downsampling. Input stages follow the recorded selection.\n"
               "Output layers and negative-parallax counts are not additive. Zero counts, if present, are labeled 0 at the axis floor.")
    return save_figure(fig, output_dir, "01_sample_counts.png", caption), plotted


def sky_coordinates(data: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    good = np.isfinite(data["l"]) & np.isfinite(data["b"]) & (np.abs(data["b"]) <= 90)
    longitude = -np.deg2rad((data["l"][good] + 180) % 360 - 180)
    latitude = np.deg2rad(data["b"][good])
    return longitude, latitude, good


def style_sky(ax: plt.Axes) -> None:
    ax.grid(alpha=0.22)
    ticks = np.deg2rad(np.arange(-150, 151, 30))
    ax.set_xticks(ticks)
    ax.set_xticklabels([f"{int(round(-np.rad2deg(x))) % 360}°" for x in ticks], fontsize=8)
    ax.set_xlabel("Galactic longitude l (increases to the left)")
    ax.set_ylabel("Galactic latitude b")


def plot_sky(run_dir: Path, output_dir: Path) -> tuple[str, dict]:
    ref = read_table(run_dir, "coverage_reference", ["l", "b", "ls_id", "source_id"])
    anchors = read_table(run_dir, "anchor", ["l", "b", "ls_id", "source_id", "partition"])
    ref_n, anchor_n = len(ref), len(anchors)
    ref = ref[sample_indices(ref)]
    drawn = anchors[sample_indices(anchors)]
    fig = plt.figure(figsize=(11.5, 9.5))
    axes = [fig.add_subplot(2, 1, i + 1, projection="mollweide") for i in range(2)]
    fig.suptitle("Sky coverage and protected spatial partitions", fontsize=16)
    lon, lat, good = sky_coordinates(ref)
    axes[0].scatter(lon, lat, s=0.5, color=GRAY, alpha=0.35, rasterized=True)
    axes[0].set_title(f"Stored coverage reference: {len(lon):,} plotted / {ref_n:,} table rows", fontsize=11)
    split_counts = {}
    for number, label, color in SPLITS:
        total = int((anchors["partition"] == number).sum())
        subset = drawn[drawn["partition"] == number]
        lon, lat, _ = sky_coordinates(subset)
        axes[1].scatter(lon, lat, s=1.0 if number != 3 else 6,
                        color=color, alpha=0.55, rasterized=True,
                        label=f"{label}: N={total:,}; drawn={len(lon):,}")
        split_counts[label] = total
    axes[1].set_title(f"Gaia-anchor table: {anchor_n:,} rows", fontsize=11)
    axes[1].legend(loc="upper center", bbox_to_anchor=(0.5, -0.13), ncol=2,
                   fontsize=9, markerscale=4, frameon=False)
    for ax in axes:
        style_sky(ax)
    caption = ("Mollweide projection of actual Galactic coordinates; at most 200,000 rows per panel, chosen by a deterministic ID hash.\n"
               "The stored reference is a coverage sample, not a full source-density map. Partition legend counts use the full anchor table.")
    return save_figure(fig, output_dir, "02_sky_partitions.png", caption, bottom=0.15), {
        "reference_rows": ref_n, "anchor_rows": anchor_n, "partitions": split_counts}


def density(ax: plt.Axes, x: np.ndarray, y: np.ndarray, bins: tuple[np.ndarray, np.ndarray],
            *, cmap: str = "Blues", vmax: float | None = None):
    finite = np.isfinite(x) & np.isfinite(y)
    counts, xe, ye = np.histogram2d(x[finite], y[finite], bins=bins)
    if not counts.any():
        empty_axis(ax)
        return None, int(finite.sum()), 0
    upper = max(2, counts.max()) if vmax is None else max(2, vmax)
    mesh = ax.pcolormesh(xe, ye, np.ma.masked_equal(counts.T, 0),
                         norm=LogNorm(vmin=1, vmax=upper), cmap=cmap, rasterized=True)
    return mesh, int(finite.sum()), int(counts.sum())


def plot_cmd(run_dir: Path, output_dir: Path) -> tuple[str, dict]:
    data = read_table(run_dir, "anchor", ["gr0", "mg", "photometry_tier"])
    fig, axes = plt.subplots(1, 2, figsize=(12.2, 6.5), gridspec_kw={"width_ratios": [1.45, 1]})
    fig.suptitle("High-quality Gaia anchors: luminosity and infrared coverage", fontsize=16)
    mesh, finite, in_bins = density(axes[0], data["gr0"], data["mg"],
                                   (np.linspace(-1, 3, 161), np.linspace(-8, 20, 141)))
    if mesh is not None:
        fig.colorbar(mesh, ax=axes[0], label="Sources per 0.025 × 0.2 mag bin", pad=0.02)
    axes[0].set(xlabel=r"$(g-r)_0$ [mag]", ylabel=r"$M_g$ [mag]",
                xlim=(-1, 3), ylim=(20, -8), title=f"CMD: {in_bins:,} in view / {finite:,} finite")
    tier_counts = [int((data["photometry_tier"] == i).sum()) for i in range(3)]
    axes[1].bar(np.arange(3), tier_counts, color=[GRAY, BLUE, ORANGE], width=0.65)
    axes[1].set_xticks(np.arange(3), ["grz only", "+ W1 only", "+ W1 + W2"])
    axes[1].set(ylabel="Anchor sources", title="Mutually exclusive photometry tiers")
    for x, value in enumerate(tier_counts):
        axes[1].annotate(f"{value:,}", (x, value), xytext=(0, 6),
                         textcoords="offset points", ha="center", fontsize=11)
    axes[1].set_ylim(0, max(1, max(tier_counts)) * 1.18)
    axes[1].grid(axis="y", alpha=0.18)
    unknown = len(data) - sum(tier_counts)
    caption = (f"All {len(data):,} anchor-table rows; no sampling. CMD excludes {len(data)-finite:,} nonfinite rows and {finite-in_bins:,} finite rows outside the shown range.\n"
               f"Infrared tiers reflect available quality measurements, not stellar types; {unknown:,} rows have an unrecognized tier. No model is fitted.")
    return save_figure(fig, output_dir, "03_anchor_cmd_ir.png", caption), {
        "rows": len(data), "cmd_finite": finite, "cmd_in_view": in_bins,
        "tier_counts": tier_counts, "unknown_tier": unknown}


def signed_bins(values: np.ndarray) -> np.ndarray:
    finite = values[np.isfinite(values)]
    extent = max(2.0, float(np.max(np.abs(finite))) * 1.001) if len(finite) else 2.0
    outer = np.geomspace(1, extent, 45)
    return np.unique(np.concatenate((-outer[::-1], np.linspace(-1, 1, 31), outer)))


def plot_parallax_noise(run_dir: Path, output_dir: Path) -> tuple[str, dict]:
    bands = ["g", "r", "z", "w1", "w2"]
    data = read_table(run_dir, "extended", ["gaia_parallax", "gaia_parallax_error", "snr_corr"]
                      + [f"sigma_{band}" for band in bands])
    valid = np.isfinite(data["gaia_parallax"]) & np.isfinite(data["gaia_parallax_error"])
    valid &= data["gaia_parallax_error"] > 0
    raw = data["gaia_parallax"][valid] / data["gaia_parallax_error"][valid]
    corrected = data["snr_corr"][np.isfinite(data["snr_corr"])]
    bins = signed_bins(np.concatenate((raw, corrected)))
    fig, axes = plt.subplots(1, 2, figsize=(13, 6.5))
    fig.suptitle("Extended Gaia sample: signed parallax and photometric noise", fontsize=16)
    for values, label, color, style in [(raw, "Raw", BLUE, "-"),
                                        (corrected, "Zero-point corrected", ORANGE, "--")]:
        if len(values):
            counts, _ = np.histogram(values, bins=bins)
            axes[0].stairs(counts, bins, label=f"{label}: N={len(values):,}",
                            color=color, linestyle=style, linewidth=1.6)
    axes[0].set_xscale("symlog", linthresh=1)
    if len(raw) or len(corrected):
        axes[0].set_yscale("log")
    else:
        empty_axis(axes[0])
    axes[0].axvline(0, color=GRAY, linewidth=1)
    axes[0].axvline(20, color=GRAY, linewidth=1, linestyle=":")
    axes[0].set(xlabel=r"Signed $\varpi/\sigma_\varpi$ (symlog)", ylabel="Sources per bin",
                title=f"Raw negative: {(raw < 0).sum():,}; exactly zero: {(raw == 0).sum():,}")
    if len(raw) or len(corrected):
        axes[0].legend(fontsize=9, frameon=False)
    errors = {}
    error_bins = np.geomspace(1e-4, 1, 81)
    for band, color, style in zip(bands, [BLUE, ORANGE, GOLD, PURPLE, GRAY], ["-", "--", "-.", ":", "-"]):
        values = data[f"sigma_{band}"]
        values = values[np.isfinite(values) & (values > 0)]
        counts, _ = np.histogram(values, bins=error_bins)
        if len(values):
            axes[1].stairs(counts, error_bins, color=color, linestyle=style,
                            linewidth=1.5,
                            label=f"{band.upper() if band.startswith('w') else band}: N={len(values):,}")
        errors[band] = {"finite_positive": len(values), "outside_view": len(values)-int(counts.sum())}
    axes[1].set_xscale("log")
    if any(item["finite_positive"] for item in errors.values()):
        axes[1].set_yscale("log")
    else:
        empty_axis(axes[1])
    axes[1].set(xlabel=r"Reported magnitude uncertainty $\sigma_m$ [mag]", ylabel="Sources per log bin",
                title="Per-band noise; nondetections are not filled in")
    if any(item["finite_positive"] for item in errors.values()):
        axes[1].legend(fontsize=9, frameon=False)
    for ax in axes:
        ax.grid(alpha=0.16)
    outside = ", ".join(f"{b} {d['outside_view']:,}" for b, d in errors.items())
    caption = (f"All {len(data):,} extended-table rows. Signed-S/N bins are linear for |S/N|≤1 and logarithmic outside; the full finite range is retained.\n"
               f"Noise uses positive finite errors; counts outside 0.0001–1 mag: {outside}. Invalid zero-point corrections are absent only from the corrected curve.")
    return save_figure(fig, output_dir, "04_extended_parallax_noise.png", caption), {
        "rows": len(data), "raw_snr_finite": len(raw), "corrected_snr_finite": len(corrected),
        "negative_raw": int((raw < 0).sum()), "zero_raw": int((raw == 0).sum()), "errors": errors}


def plot_spectroscopy(run_dir: Path, output_dir: Path) -> tuple[str, dict]:
    columns = ["anchor"] + [f"{survey}_{value}" for survey in ("desi", "apogee")
                             for value in ("teff", "logg", "feh", "quality")]
    data = read_table(run_dir, "spectroscopy", columns)
    masks, stats = {}, {}
    for survey in ("desi", "apogee"):
        good = data[f"{survey}_quality"].astype(bool)
        for value in ("teff", "logg", "feh"):
            values = data[f"{survey}_{value}"]
            good &= np.isfinite(values) & (values > (-9000 if value != "teff" else 0))
        masks[survey] = good
    # Common limits and bins allow visual comparison; independent surveys are
    # never averaged into a shared metallicity label.
    def bounds(field: str, fallback: tuple[float, float]) -> tuple[float, float]:
        arrays = [data[f"{s}_{field}"][masks[s]] for s in masks]
        values = np.concatenate(arrays)
        if not len(values):
            return fallback
        lo, hi = float(values.min()), float(values.max())
        pad = max((hi-lo) * 0.02, 0.01 if field != "teff" else 50)
        return lo-pad, hi+pad
    teff_range = bounds("teff", (3000, 9000))
    logg_range = bounds("logg", (-0.5, 5.5))
    feh_range = bounds("feh", (-4, 1))
    teff_bins = np.linspace(*teff_range, 101)
    logg_bins = np.linspace(*logg_range, 101)
    feh_bins = np.linspace(*feh_range, 66)
    maximum = max(2, *(np.histogram2d(data[f"{s}_teff"][masks[s]], data[f"{s}_logg"][masks[s]],
                                     bins=(teff_bins, logg_bins))[0].max() for s in masks))
    fig, axes = plt.subplots(2, 2, figsize=(12.3, 9))
    fig.suptitle("Spectroscopic auxiliary coverage — survey labels remain separate", fontsize=16)
    for row, (survey, color) in enumerate([( "desi", BLUE), ("apogee", ORANGE)]):
        good = masks[survey]
        overlap = good & data["anchor"].astype(bool)
        mesh, _, _ = density(axes[row, 0], data[f"{survey}_teff"][good],
                              data[f"{survey}_logg"][good], (teff_bins, logg_bins),
                              cmap="Blues", vmax=maximum)
        if mesh is not None:
            fig.colorbar(mesh, ax=axes[row, 0], label="Sources per bin (shared scale)", pad=0.02)
        axes[row, 0].set(xlabel=r"$T_{\rm eff}$ [K]", ylabel=r"$\log g$ [dex]",
                         xlim=teff_range[::-1], ylim=logg_range[::-1],
                         title=f"{survey.upper()}: quality N={good.sum():,}")
        for mask, label, style in [(good, "Quality auxiliary sample", "-"),
                                    (overlap, "Meets Gaia-anchor selection", "--")]:
            if mask.any():
                counts, _ = np.histogram(data[f"{survey}_feh"][mask], bins=feh_bins)
                axes[row, 1].stairs(counts, feh_bins, color=color, linestyle=style,
                                    linewidth=1.8, label=f"{label}: N={mask.sum():,}")
        if good.any():
            axes[row, 1].set_yscale("log")
            peak = np.histogram(data[f"{survey}_feh"][good], bins=feh_bins)[0].max()
            axes[row, 1].set_ylim(0.8, max(2, peak) * 6)
            axes[row, 1].legend(fontsize=9, loc="upper left", frameon=False)
        else:
            empty_axis(axes[row, 1])
        axes[row, 1].set(xlabel=r"Spectroscopic [Fe/H] [dex]", ylabel="Sources per common bin",
                         xlim=feh_range, title=f"{survey.upper()}: metallicity coverage")
        axes[row, 1].grid(alpha=0.16)
        stats[survey] = {"quality_finite": int(good.sum()), "gaia_anchor_overlap": int(overlap.sum())}
    caption = (f"Full spectroscopy table: {len(data):,} rows; all finite, survey-quality parameter triples are binned, without downsampling.\n"
               "Kiel diagrams share bin edges and color scale. Surveys may overlap; their counts are not additive and [Fe/H] values are not merged.\n"
               "Gaia overlap denotes selection membership, including reserved tests; spectroscopy is auxiliary information, not independent distance truth.")
    return save_figure(fig, output_dir, "05_spectroscopic_coverage.png", caption, bottom=0.14), stats


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--manifest-path", type=Path,
                        default=Path("manifests/stage1_plot_manifest.json"))
    args = parser.parse_args()
    summary_path = args.run_dir / "summary.json"
    summary = json.loads(summary_path.read_text())
    args.output_dir.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.titlepad": 12, "savefig.bbox": None})
    figures, diagnostics = [], {}
    path, stats = plot_counts(summary, args.output_dir)
    figures.append(path)
    diagnostics["counts"] = stats
    for name, function in [("sky", plot_sky), ("cmd", plot_cmd),
                           ("extended", plot_parallax_noise), ("spectroscopy", plot_spectroscopy)]:
        path, stats = function(args.run_dir, args.output_dir)
        figures.append(path)
        diagnostics[name] = stats
    manifest = {"run_dir": str(args.run_dir.resolve()), "summary": str(summary_path.resolve()),
                "scatter_sampling": "splitmix64 of IDs, maximum 200000 rows per panel",
                "histograms": "all eligible finite measurements from each named FITS table",
                "figures": [Path(path).name for path in figures], "diagnostics": diagnostics}
    args.manifest_path.parent.mkdir(parents=True, exist_ok=True)
    args.manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"figures": figures, "manifest": str(args.manifest_path)}))


if __name__ == "__main__":
    main()
